def make_tg(city_part, parts):
    stems = []
    for p in parts:
        p = p.lower().replace(" ","_").replace(",","").replace("'","").replace("-","_")
        stems.append(p)
    # 80% use city suffix
    if random.random() < 0.85:
        s = random.choice(stems) + "_" + city_part
    else:
        s = "_".join(stems)
    # ensure not just single word
    if "_" not in s:
        s = s + "_" + city_part
    s = s.strip("_")
    if len(s) > 30:
        s = s[:30].rstrip("_")
    return s

